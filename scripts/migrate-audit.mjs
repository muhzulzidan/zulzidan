import { neon } from "@neondatabase/serverless";

const connectionString =
  process.env.DATABASE_URL || process.env.POSTGRES_URL;

if (!connectionString) {
  throw new Error("DATABASE_URL or POSTGRES_URL must be configured.");
}

const sql = neon(connectionString);

await sql`
  CREATE TABLE IF NOT EXISTS audit_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL,
    website_url TEXT NOT NULL,
    main_concern TEXT,
    status VARCHAR(32) NOT NULL DEFAULT 'new',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  )
`;

await sql`
  CREATE INDEX IF NOT EXISTS audit_requests_created_at_idx
  ON audit_requests (created_at DESC)
`;

await sql`
  CREATE INDEX IF NOT EXISTS audit_requests_email_idx
  ON audit_requests (LOWER(email))
`;

console.log("Audit request database migration completed.");
