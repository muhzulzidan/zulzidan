import { neon } from "@neondatabase/serverless";

const connectionString =
  process.env.DATABASE_URL || process.env.POSTGRES_URL;

if (!connectionString) {
  throw new Error("DATABASE_URL or POSTGRES_URL must be configured.");
}

const sql = neon(connectionString);

await sql`
  CREATE TABLE IF NOT EXISTS project_inquiries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL,
    organization VARCHAR(160) NOT NULL,
    website_url TEXT,
    plan VARCHAR(32) NOT NULL,
    first_priority TEXT NOT NULL,
    start_window VARCHAR(32) NOT NULL,
    source VARCHAR(120) NOT NULL DEFAULT '/start/',
    status VARCHAR(32) NOT NULL DEFAULT 'new',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  )
`;

await sql`
  CREATE INDEX IF NOT EXISTS project_inquiries_created_at_idx
  ON project_inquiries (created_at DESC)
`;

await sql`
  CREATE INDEX IF NOT EXISTS project_inquiries_email_idx
  ON project_inquiries (LOWER(email))
`;

console.log("Project inquiry database migration completed.");
